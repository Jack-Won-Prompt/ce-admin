    ];

    /** 어느 쪽도 아닌 것 */
    public const OTHER = [
        '관리자 확인 - 시스템 issue(판매 주문부터 시작/확정)',
        '재고부족으로 발송지연',
        '카카오구매-요양병원',
    ];

    /**
     * 전문과목 (요청서 12쪽).
     *
     * 자유롭게 적게 두었더니 「비뇨기과」ㆍ「비뇨의학과」ㆍ「비뇨기과의원」이 한 표에
     * 섞여 과목별로 세어지지 않았다. 요청서에 「비뇨기과」가 두 번 적혀 있는데
     * 같은 말이라 한 줄로 둔다 — 확인이 필요하면 여기만 고치면 된다.
     */
    public const SPECIALTIES = [
        '비뇨기과',
        '재활의학과',
        '정형외과',
        '신경과 또는 신경외과',
    ];

    /** 화면이 optgroup 으로 그릴 수 있게 묶어 준다 */
    public static function groups(): array
    {
        return [
            '진행중' => self::PROGRESS,
            '취소'   => self::CANCELLED,
            '기타'   => self::OTHER,
        ];
    }

    public static function all(): array
    {
        return array_merge(self::PROGRESS, self::CANCELLED, self::OTHER);
    }

    /** 목록에 없는 값인가 — 위드웍스에서 옮겨 온 것은 그 건에서만 함께 세운다 */
    public static function isKnown(?string $value): bool
    {
        return $value !== null && $value !== '' && in_array($value, self::all(), true);
    }
}
