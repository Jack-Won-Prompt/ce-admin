 * 두면 「미입금」과 「입금 안 됨」과 「돈 안 들어옴」이 한 표에 섞여 세어지지 않는다.
 *
 * 진행중과 취소를 갈라 둔다 — 앞엣것은 아직 살아 있는 건이고 뒤엣것은 닫힌 건이다.
 * 목록에서 그 둘이 섞여 있으면 무엇을 고르는지 눈으로 가리기 어렵다.
 */
class OrderReason
{
    /** 아직 살아 있는 건 — 왜 멈춰 있는가 */
    public const PROGRESS = [
        '진행중-재구매일자대기',
        '진행중-샘플진행중',
        '진행중-재고여유',
        '진행중-입원중',
        '진행중-통화연결실패',
        '진행중-미입금',
        '진행중-유치도뇨',
        '진행중-입금대기 또는 대리점 판매확정 미진행 예상',
        '진행중-대리점이 사유 확인중',
        '진행중-출국',
