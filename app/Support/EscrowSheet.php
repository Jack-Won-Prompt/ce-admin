<?php

namespace App\Support;

use App\Models\Order;
use App\Models\Patient;
use App\Models\TossPayment;

/**
 * 토스페이먼츠 에스크로 배송정보 엑셀 — 양식과 값을 한 곳에서 정한다.
 *
 * ## 왜 필요한가
 *
 * 에스크로 결제는 **배송정보를 등록하거나 구매자가 구매확정을 해야** 정산이 돈다.
 * 등록하지 않으면 돈이 들어오지 않는다 (SR #141 「토스에 상품 전달･배송 정보 입력을
 * 해야 정산 금액 입금 되는 것 같습니다」). 여태 담당자가 토스 상점관리자에서 건마다
 * 손으로 적었다.
 *
 * ## 양식 — **아직 못 박지 못했다**
 *
 * 토스 상점관리자의 「배송정보 한 번에 등록하기」가 내려 주는 **빈 양식**이 정본인데,
 * 그 양식의 칸 이름ㆍ차례는 토스 공개 문서에 적혀 있지 않다(2026-10-13 확인). 그래서
 * 지금 아는 것으로 세웠다 — 2026-10-07 에 담당자가 올려 준 「에스크로 결제내역」
 * 내려받기 파일(SR #141 첨부)의 **열한 칸을 그대로** 두고, 뒤에 적어 넣을 세 칸
 * (택배사ㆍ송장번호ㆍ발송일시)과 우리 쪽 확인용 두 칸을 붙였다.
 *
 * 열한 칸을 그대로 둔 까닭은 토스 안내가 그 양식을 「배송정보가 등록되지 않은 주문건만
 * 모아 다운로드」한 것이라 하기 때문이다 — 곧 같은 꼴일 가능성이 높다. 첨부 파일에서
 * 「배송정보 등록일ㆍ배송완료일ㆍ구매확정·취소일ㆍ자동 구매확정일」 네 칸은 스물다섯
 * 줄 모두 비어 있었다. 우리도 비워 둔다 — 그 값은 토스만 안다.
 *
 * **담당자가 한 번 올려 보고 어긋나면 빈 양식을 받아 이 자리만 고친다.** 양식에 관한
 * 결정은 모두 이 파일 안에 있다.
 */
class EscrowSheet
{
    /**
     * 택배사.
     *
     * 우리 자료에는 택배사 칸이 **없다** — 표를 다 훑어도 없다(2026-10-13 확인).
     * 창고(위드웍스)가 CJ 로만 내보내고 송장번호도 「6006-7119-9303」처럼 CJ 꼴이다.
     * 그래서 한 값으로 적는다. 택배사가 둘 이상이 되면 칸을 만들어야 한다.
     */
    public const 택배사 = 'CJ대한통운';

    /**
     * 발송일시 꼴.
     *
     * 2026-10-08 에 손으로 만들어 쓰던 목록이 「발송일시(YYYYMMDDhhmm)」였다. 그 꼴을
     * 잇는다 — 시ㆍ분은 우리가 모르므로(출고일만 안다) 0000 으로 둔다.
     */
    public const 발송일꼴 = 'YmdHi';

    /** 머리글 — 앞의 열한 칸은 토스가 내려 준 파일 그대로다 */
    public const 머리글 = [
        '상점아이디(MID)', '결제일시', '주문번호', '에스크로 상태', '금액', '구매자명',
        '배송정보 등록일', '배송완료일', '구매확정·취소일', '자동 구매확정일', '구매상품',
        /* ── 여기부터 우리가 적어 넣는 칸 ─────────────────────────────── */
        '택배사', '송장번호', '발송일시',
        /* ── 우리 쪽 확인용. 토스가 뒤의 칸을 싫어하면 이 둘을 떼면 된다 ── */
        '우리 주문번호', '출고 상태',
    ];

    /**
     * 숫자로 담을 칸(0부터).
     *
     * 금액만이다. 주문번호ㆍ송장번호를 숫자로 담으면 엑셀이 지수꼴로 보이거나 앞의
     * 0 을 지운다.
     */
    public const 숫자칸 = [4];

    /**
     * 이 주문이 에스크로 배송정보를 등록할 차례인가.
     *
     * 세 가지를 본다 —
     *
     *   · 토스 결제 줄이 있고
     *   · 그 결제가 **에스크로**이고(`useEscrow`. 카드는 에스크로를 쓰지 않는다)
     *   · 결제가 **끝났고**(DONE)
     *
     * 입금 기다리는 건(WAITING_FOR_DEPOSIT)과 취소된 건은 담지 않는다 — 등록할 것이
     * 없다. 운영에서 에스크로 결제 47건 가운데 그런 것이 있다(2026-10-13).
     *
     * 송장이 아직 없는 건은 **담는다.** 빈 칸으로 서고 「출고 상태」가 왜 비었는지
     * 알려 준다 — 빼 버리면 담당자가 다 끝난 줄 안다.
     */
    public static function 담을것인가(?TossPayment $결제): bool
    {
        if (! $결제 || $결제->status !== 'DONE') {
            return false;
        }

        $원본 = $결제->raw_response;

        return is_array($원본) && ($원본['useEscrow'] ?? false) === true;
    }

    /**
     * 한 줄.
     *
     * @return string[]|null 담을 차례가 아니면 null
     */
    public static function 줄(Order $주문): ?array
    {
        $결제 = $주문->tossPayment;

        if (! self::담을것인가($결제)) {
            return null;
        }

        $원본 = is_array($결제->raw_response) ? $결제->raw_response : [];

        /* 송장번호는 **숫자만** 적는다. 2026-10-08 목록이 「송장번호(숫자만)」 칸을
           따로 두었다 — 가운데 줄표가 든 꼴은 받지 않는 듯하다. */
        $송장 = preg_replace('/\D/', '',
            (string) ($주문->tracking_number ?: $주문->withworks_tracking_no)) ?? '';

        /* 발송일 — 우리 출고일이 먼저고, 없으면 창고가 알려 준 날을 쓴다 */
        $발송 = $주문->shipped_at ?: $주문->withworks_ship_at;

        /* 송장과 발송일이 **둘 다** 있어야 등록이 선다. 하나만 있으면 둘 다 비워 둔다 —
           반만 적힌 줄을 올리면 토스가 무엇을 되돌려줄지 알 수 없다. */
        $등록가능 = $송장 !== '' && $발송;

        return [
            (string) ($원본['mId'] ?? ''),
            self::날짜글($원본['approvedAt'] ?? null) ?: (string) $결제->deposited_at?->format('Y-m-d H:i:s'),
            (string) $결제->toss_order_id,
            '',                                     // 에스크로 상태 — 토스만 안다
            (int) $결제->amount,
            /* 「(E)」는 우리끼리 쓰는 사업부 표시다 — 떼고 적는다 (2026-09-27 지시) */
            Patient::실명($주문->patient?->name) ?: (string) $주문->shipping_recipient,
            '',                                     // 배송정보 등록일  ┐
            '',                                     // 배송완료일       ├ 토스만 안다
            '',                                     // 구매확정·취소일  │
            '',                                     // 자동 구매확정일  ┘
            /* 토스가 쥐고 있는 상품명을 그대로 쓴다 — 저쪽 줄과 맞춰 보기 쉽다 */
            (string) ($원본['orderName'] ?? $주문->상품한마디()),
            $등록가능 ? self::택배사 : '',
            $등록가능 ? $송장 : '',
            $등록가능 ? $발송->format(self::발송일꼴) : '',
            (string) $주문->order_number,
            (string) ($주문->withworks_ship_status_label ?: $주문->status_label),
        ];
    }

    /**
     * 토스가 주는 때(ISO 8601 · 「2026-10-07T16:44:07+09:00」)를 사람이 읽는 꼴로.
     *
     * 내려받은 파일이 「2026-10-07 16:44:07」이라 그 꼴을 맞춘다.
     */
    private static function 날짜글(mixed $값): string
    {
        $글 = trim((string) $값);

        if ($글 === '') {
            return '';
        }

        try {
            return \Illuminate\Support\Carbon::parse($글)->format('Y-m-d H:i:s');
        } catch (\Throwable) {
            return $글;
        }
    }
}
