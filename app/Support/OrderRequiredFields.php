namespace App\Support;

use App\Models\Order;
use App\Models\Prescription;

/**
 * 「1일 처방 개수ㆍ총 처방일수ㆍ유형ㆍ자격이 채워져야 저장ㆍ주문연계가 된다」
 * (2026-10-08 지시 · SR #148).
 *
 * 여태 막는 자리가 **화면의 제품 넣기 한 곳**뿐이었다(gate필수칸 · SR #76, 10-06).
 * 보는 것도 유형ㆍ신구매/재구매ㆍ자격 셋이었고 1일 처방 개수ㆍ총 처방일수는 아예
 * 보지 않았다. 저장도 연계도 그대로 지나갔다 — 화면만 막으면 이렇게 샌다.
 *
 * 실제로 듣지 않았다. 잣대를 세운 10-06 12시 앞뒤로 갈라 세어 보니(2026-10-08 운영)
 *
 *   세우기 전 194건 중 넷 가운데 하나라도 빈 것 69건 (창고로 간 것 12)
 *   세운 뒤   203건 중                        94건 (창고로 간 것 14)
 *
 * 줄기는커녕 늘었다. 그래서 **서버에서** 막는다 — 저장과 연계 두 곳 모두.
 *
 * ── 처방외는 넷을 다 묻지 않는다
 * 처방외(20)는 처방전이 없이 파는 갈래라 자격ㆍ처방 개수ㆍ처방일수가 애초에 없다.
 * 운영 처방외 주문 29건은 **29건 모두** 1일 개수와 총 일수가 비어 있다(2026-10-08).
 * 요구하면 처방외는 한 건도 못 판다. 처방외에는 유형만 묻는다.
 * (화면의 gate필수칸 도 처방외에서는 자격을 묻지 않는다 — 같은 잣대다.)
 *
 * ── 이미 선 건은 지나보낸다
 * 잣대를 세우던 날 아직 창고로 넘기지 않은 주문 가운데 넷이 모자란 것이 131건이었다.
 * 그 줄들을 한꺼번에 막으면 담당자가 손도 못 댄다. **적용시작 뒤에 선 주문만** 본다.
 * 이미 있는 것은 목록으로 뽑아 따로 메운다(2026-10-08 지시 「다」).
 */
class OrderRequiredFields
{
    /**
     * 이 시각 **뒤에 선 주문**부터 막는다.
     *
     * 앞서 선 건은 지나보낸다 — 막아 봐야 메울 길은 같은데 손만 묶인다.
     */
    public const 적용시작 = '2026-10-08 15:00:00';

    /** 처방외 — 자격ㆍ처방 개수ㆍ처방일수를 쓰지 않는 갈래 */
    private const 처방외 = '20';

    /**
     * 이 처방전에 모자란 칸의 이름들. 비어 있으면 다 채워진 것이다.
     *
     * 화면이 보낸 값으로도 가릴 수 있게 $들어온값 을 받는다 — 저장하기 전에 막아야
     * 한 칸도 바뀌지 않는다(SR #79 의 신구매 관문과 같은 자리).
     */
    public static function 모자란것(?Prescription $rx, array $들어온값 = []): array
    {
        if (! $rx) {
            return [];
        }

        $값 = function (string $칸) use ($rx, $들어온값) {
            return array_key_exists($칸, $들어온값) ? $들어온값[$칸] : $rx->{$칸};
        };

        $빔 = fn ($v) => trim((string) $v) === '';

        $유형 = (string) $값('counsel_acc_add_type');

        $모자람 = [];

        if ($빔($유형)) {
            $모자람[] = '유형';
        }

        /* 처방외는 여기까지다 — 아래 셋은 처방전이 있어야 나오는 값이다 */
        if ($유형 === self::처방외) {
            return $모자람;
        }

        if ($빔($값('benefit_class')))              { $모자람[] = '자격'; }
        if ((int) $값('daily_count') <= 0)          { $모자람[] = '1일 처방 개수'; }
        if ((int) $값('total_days')  <= 0)          { $모자람[] = '총 처방일수'; }

        return $모자람;
    }

    /**
     * 지금 이 주문을 막아야 하는가 — 막아야 하면 모자란 칸 이름들을 돌려준다.
     *
     * 적용시작 앞에 선 주문은 빈 배열이다(지나보낸다).
     */
    public static function 막을것(?Order $order, ?Prescription $rx, array $들어온값 = []): array
    {
        if ($order && $order->created_at && $order->created_at->lt(self::적용시작)) {
            return [];
        }

        return self::모자란것($rx, $들어온값);
    }

    /** 사람에게 보일 한 줄 */
    public static function 말(array $모자람): string
    {
        return implode('ㆍ', $모자람)
             . '이(가) 비어 있습니다. 네 가지(유형ㆍ자격ㆍ1일 처방 개수ㆍ총 처방일수)가 모두 채워져야 '
             . '주문을 저장하고 창고로 넘길 수 있습니다. (처방외는 유형만 필요합니다)';
    }
}
