# **TC 차례로 세운다.** 파일 번호는 그날 찍은 차례라 시나리오 차례와 어긋난다
# (팩스를 맨 뒤에 찍었지만 TC 로는 동의 바로 뒤다). 이 시트는 시나리오 시트와
# 나란히 놓고 보는 것이므로, 같은 차례로 서야 짚어 가며 읽을 수 있다.
def _캡키(c):
    _파, _tc = c[0], c[1]
    번호 = ''
    for ch in _파:
        if ch.isdigit():
            번호 += ch
        else:
            break
    꼬리 = _파[len(번호):len(번호) + 1]
    if _tc == '사전':
        return (0, 0, '', int(번호 or 0), 꼬리)
    t = _tc.replace('TC-', '')
