def 돈(v):
    return '{:,}'.format(int(float(v or 0))) + '원'


def 전화(raw):
    """화면이 보여 주는 꼴로 편다 — App\Support\PhoneNo 와 같은 잣대."""
    import re as _re
    raw = (raw or '').strip()
    if not raw:
        return '—'
    d = _re.sub(r'\D', '', raw)
    if d.startswith('050') and len(d) > 3 and d[3].isdigit():
        if len(d) == 12:
            return d[:4] + '-' + d[4:8] + '-' + d[8:]
        if len(d) == 11:
            return d[:4] + '-' + d[4:7] + '-' + d[7:]
        return raw
    if _re.match(r'^\d{2,4}-\d{3,4}-\d{4}$', raw):
        return raw
    if len(d) == 11 and d.startswith('0'):
        return d[:3] + '-' + d[3:7] + '-' + d[7:]
    if len(d) == 10 and d.startswith('02'):
        return '02-' + d[2:6] + '-' + d[6:]
    if len(d) == 10 and d.startswith('0'):
        return d[:3] + '-' + d[3:6] + '-' + d[6:]
    if len(d) == 9 and d.startswith('02'):
        return '02-' + d[2:5] + '-' + d[5:]
    if len(d) == 8:
        return d[:4] + '-' + d[4:]
    return raw


